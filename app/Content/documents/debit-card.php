<h1>Serendib Debit</h1>
<p class="document-lead">Make everyday purchases using money available in your linked SerendibBank account.</p>
<div class="document-rule"></div>
<h2>How it works</h2>
<p>A debit card is linked to an eligible account. Purchases and withdrawals reduce the available balance of that account.</p>
<h2>Keeping track</h2>
<p>Use online banking to review your account activity. Keep your PIN and card details private, and tell us promptly if you see an unfamiliar transaction.</p>
<h2>Applying</h2>
<p>If you have an eligible account, you can submit a card application from online banking. A team member will review your request.</p>
<p class="document-note">Card availability, limits, charges and terms are confirmed during the application process.</p>

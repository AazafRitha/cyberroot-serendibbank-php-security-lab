<h2>At a glance</h2>
<p>View your balance and recent activity through online banking. You can ask about a linked debit card and use your account for everyday payments and deposits.</p>
<h2>Opening an account</h2>
<p>Send an application through online banking. Our team may contact you to confirm your details and explain what documents are needed before an account is opened.</p>
<h2>Using your account</h2>
<p>Check account activity regularly. If you notice a payment you do not recognise, contact us through a verified channel as soon as possible.</p>
<p class="document-note">For current charges, eligibility and full terms, speak with our team before applying.</p>

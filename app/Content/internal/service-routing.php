<h1>Digital service routing</h1>
<p class="document-lead">Service queue guidance for customer care staff.</p>
<div class="document-rule"></div>
<h2>Priority handling</h2>
<p>Reports involving digital access or an unfamiliar account action should be reviewed by the digital service queue <strong>DIGITAL-PRIORITY-42</strong>. Record the customer's preferred contact channel and the time the issue was reported.</p>
<h2>Customer communication</h2>
<p>Never ask a customer to disclose a password, PIN or one-time code. Direct urgent card concerns to the card support team.</p>
